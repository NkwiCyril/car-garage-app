@Injectable({ providedIn: 'root' })
export class TranslationService {
  private langSubject: BehaviorSubject<string>;

  constructor() {
    const saved = localStorage.getItem('app_language') ?? 'en';
    this.langSubject = new BehaviorSubject<string>(saved);
  }

  get lang$(): Observable<string> {
    return this.langSubject.asObservable();
  }

  get currentLang(): string {
    return this.langSubject.value;
  }

  setLanguage(code: string): void {
    localStorage.setItem('app_language', code);
    this.langSubject.next(code);
  }

  t(key: string): string {
    const dict = TRANSLATIONS[this.langSubject.value] ?? TRANSLATIONS['en'];
    return dict[key] ?? TRANSLATIONS['en'][key] ?? key;
  }
}
